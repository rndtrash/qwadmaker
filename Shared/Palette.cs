        public static Rgba32[] Read(Stream input)
        {
            return [.. Enumerable.Range(0, Constants.MaxPaletteSize).Select(i => input.ReadColor())];
        }

        public static Rgba32[] Read(string path)
        {
            using var stream = File.OpenRead(path);
            return Read(stream);
        }

        public static Rgba32[] From(byte[] array)
        {
            var expectedSize = Constants.MaxPaletteSize * 3;
            if (array.Length != expectedSize)
            {
                throw new Exception($"Invalid palette byte array size (Expected {expectedSize}, got {array.Length})");
            }

            using var stream = new MemoryStream(array);
            return Read(stream);
        }

        public static void Write(Stream output, Rgba32[] palette)
        {
            if (palette.Length != Constants.MaxPaletteSize)
            {
                throw new Exception($"Attempted to write a non-standard palette (expected {Constants.MaxPaletteSize} colors, got {palette.Length})");
            }

            foreach (var color in palette)
            {
                output.Write(color);
            }
        }
